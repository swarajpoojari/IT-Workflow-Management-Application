import { env } from '../config/env.js';

/**
 * Outbound mail, stubbed.
 *
 * There is no SMTP transport wired into this project — deliberately, so the app
 * runs with Node and nothing else. Every message is written to the server
 * console instead, in the shape a real transport would receive. Swapping in
 * nodemailer later means replacing `deliver()` and nothing above it.
 */
function deliver({ to, subject, body }) {
  if (env.isTest) return { delivered: false, transport: 'noop' };

  const rule = '─'.repeat(64);
  console.log(`\n📧 ${rule}`);
  console.log(`   To:      ${to}`);
  console.log(`   Subject: ${subject}`);
  console.log(rule);
  console.log(body.split('\n').map((line) => `   ${line}`).join('\n'));
  console.log(`${rule}\n`);

  return { delivered: true, transport: 'console' };
}

export const mailer = {
  /**
   * The invite an admin triggers by creating a user. The temporary password is
   * generated by the caller, stored only as a hash, and shown to the admin once.
   */
  sendUserInvite({ email, fullName, temporaryPassword, roleName, invitedBy }) {
    return deliver({
      to: email,
      subject: 'Your IT Workflow account is ready',
      body: [
        `Hello ${fullName},`,
        '',
        `${invitedBy ?? 'An administrator'} created an IT Workflow account for you`,
        `with the role "${roleName}".`,
        '',
        `  Sign-in email:      ${email}`,
        `  Temporary password: ${temporaryPassword}`,
        '',
        'Sign in with the temporary password and set a password of your own.',
        'The temporary password stops working once you do.',
      ].join('\n'),
    });
  },
};
